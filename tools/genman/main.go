// Command genman writes the man pages of git-id (git-id.1, git-id-use.1, ...).
// git runs `man git-id` for `git id --help`, so the pages must be installed
// where man finds them; `make install` does that.
//
//	go run ./tools/genman <output-dir>
package main

import (
	"fmt"
	"os"

	"github.com/spf13/cobra/doc"

	"git-id/internal/cli"
)

func main() {
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "usage: genman <output-dir>")
		os.Exit(2)
	}
	dir := os.Args[1]
	if err := os.MkdirAll(dir, 0o755); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	root := cli.NewRootCmd()
	root.DisableAutoGenTag = true // no "auto generated by cobra" footer
	hdr := &doc.GenManHeader{Title: "GIT-ID", Section: "1", Source: "git-id"}
	if err := doc.GenManTree(root, hdr, dir); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
